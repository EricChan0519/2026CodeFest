export const fill = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''))

/** 距離的說法：100 公尺以上取到 10 公尺；10–100 取到 5 公尺；不到 10 公尺「快到了」（01 產品規格） */
export function distanceWords(m: number | null, lang: Lang): string {
  const s = ARROW_STRINGS[lang]
  if (m === null) return '—'
  if (m < 10) return s.almost
  if (m >= 1000) return fill(s.km, { n: (m / 1000).toFixed(1) })
  const r = m >= 100 ? Math.round(m / 10) * 10 : Math.round(m / 5) * 5
  return fill(s.meters, { n: r })
}
